fn family(chip: &str) -> Option<Fam> {
    Some(match chip.to_ascii_uppercase().as_str() {
        "IT8705F" | "IT8712F" | "IT8716F" | "IT8718F" | "IT8720F" | "IT8726F" => IteA,
        "IT8613E" | "IT8620E" | "IT8625E" | "IT8628E" | "IT8631E" | "IT8638E" | "IT8655E" | "IT8665E" | "IT8686E"
        | "IT8688E" | "IT8689E" | "IT8721F" | "IT8728F" | "IT8771E" | "IT8772E" | "IT8696E" => IteB,
        "IT87952E" | "IT8792E" | "IT8790E" => IteC,
        "F71808E" | "F71862" | "F71869" | "F71869A" | "F71882" | "F71889AD" | "F71889ED" | "F71889F" => Fintek,
        "NCT6771F" | "NCT6776F" => NuvF,
        "NCT5585D" => Nct5585,
        "NCT610XD" => Nct610x,
        "NCT6779D" | "NCT6791D" | "NCT6792D" | "NCT6792DA" | "NCT6793D" | "NCT6795D" | "NCT6796D" | "NCT6796DR"
        | "NCT6796DS" | "NCT6797D" | "NCT6798D" | "NCT6799D" | "NCT6701D" | "NCT6683D" => NuvD,
        "NCT6686D" | "NCT6687D" => Nct668x,
        "NCT6687DR" => Nct6687DR,
        _ => return None,
    })
}

/// Producenci płyt z konfiguracjami w LHM.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Maker {
    /// Dowolny producent (NCT6687D-R w LHM sprawdza tylko model).
    Any,
    Asus,
    AsRock,
    Biostar,
    Dfi,
    Ecs,
    Evga,
    Gigabyte,
    Msi,
    Shuttle,
    Supermicro,
}

use Maker::*;

/// Producent jak `Identification.GetManufacturer` (tylko ci z konfiguracjami).
fn maker(name: &str) -> Option<Maker> {
    let is = |s: &str| name.eq_ignore_ascii_case(s);
    let starts = |s: &str| name.get(..s.len()).is_some_and(|p| p.eq_ignore_ascii_case(s));
    Some(match () {
        _ if is("ASRock") => AsRock,
        _ if starts("ASUSTeK") || starts("ASUS ") => Asus,
        _ if starts("Biostar") => Biostar,
        _ if is("DFI") || starts("DFI Inc") => Dfi,
        _ if is("ECS") || starts("ELITEGROUP") => Ecs,
        _ if starts("EVGA") => Evga,
        _ if starts("Gigabyte") => Gigabyte,
        _ if starts("Micro-Star International") || is("MSI") => Msi,
        _ if starts("Shuttle") => Shuttle,
        _ if starts("Supermicro") => Supermicro,
        _ => return None,
    })
}

/// Model jak `Identification.GetModel` (pierwsze trafienie wygrywa).
fn model(name: &str) -> Option<&'static str> {
    MODELS
        .iter()
        .find(|(s, _, prefix)| {
            if *prefix {
                name.get(..s.len()).is_some_and(|p| p.eq_ignore_ascii_case(s))
            } else {
                name.eq_ignore_ascii_case(s)
            }
        })
        .map(|(_, m, _)| *m)
}

/// Który układ płyty (`superIOIndex` w LHM).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Idx {
    Any,
    First,
    Other,
}

/// Konfiguracja LHM: grupa układów, producent, modele (pusta lista - każdy
/// model tego producenta) i lista czujników.
struct Cfg {
    fam: Fam,
    maker: Maker,
    models: &'static [&'static str],
    index: Idx,
    s: &'static [S],
}

const fn c(fam: Fam, maker: Maker, models: &'static [&'static str], s: &'static [S]) -> Cfg {
    Cfg { fam, maker, models, index: Idx::Any, s }
}

