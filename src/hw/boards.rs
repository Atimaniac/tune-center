/// Liczby czujników układu (`Temperatures.Length`, `Fans.Length`, `Controls.Length` w LHM).
#[derive(Clone, Copy, Debug)]
pub struct Counts {
    pub temps: usize,
    pub fans: usize,
    pub controls: usize,
}

/// Czujniki pokazywane na danej płycie: (indeks, nazwa) w kolejności LHM.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct BoardNames {
    pub temps: Vec<(usize, String)>,
    pub fans: Vec<(usize, String)>,
    pub controls: Vec<(usize, String)>,
}

/// Nazwy dla płyty albo `None`, gdy LHM używa dla tego układu konfiguracji
/// domyślnej (zostają domyślne listy sterownika).
///
/// `chip` - nazwa z wyliczenia `Chip` w LHM (np. "NCT6798D", "IT8688E"),
/// `manufacturer`/`product` - BaseBoardManufacturer/BaseBoardProduct z SMBIOS,
/// `index` - numer układu wśród wykrytych układów Super I/O (drugi układ płyty).
pub fn names(chip: &str, manufacturer: &str, product: &str, index: usize, counts: Counts) -> Option<BoardNames> {
    let fam = family(chip)?;
    let maker = maker(manufacturer.trim());
    let model = model(product.trim());
    let cfg = CONFIGS.iter().find(|c| {
        c.fam == fam
            && (c.maker == Maker::Any || Some(c.maker) == maker)
            && (c.models.is_empty() || model.is_some_and(|m| c.models.contains(&m)))
            && match c.index {
                Idx::Any => true,
                Idx::First => index == 0,
                Idx::Other => index != 0,
            }
    })?;
    Some(expand(cfg.s, counts))
}

/// Rozwija pętle i pomija indeksy spoza układu.
fn expand(items: &[S], n: Counts) -> BoardNames {
    let mut b = BoardNames::default();
    let fixed = |out: &mut Vec<(usize, String)>, i: usize, name: &str, count: usize| {
        if i < count {
            out.push((i, name.to_string()));
        }
    };
    let looped =
        |out: &mut Vec<(usize, String)>, from: usize, count: usize, prefix: &str, offset: isize, skip: &[usize]| {
            for i in from..count {
                if !skip.contains(&i) {
                    out.push((i, format!("{prefix}{}", i as isize + offset)));
                }
            }
        };
    for item in items {
        match *item {
            T(i, name) => fixed(&mut b.temps, i, name, n.temps),
            F(i, name) => fixed(&mut b.fans, i, name, n.fans),
            C(i, name) => fixed(&mut b.controls, i, name, n.controls),
            TL(from, prefix, offset) => looped(&mut b.temps, from, n.temps, prefix, offset, &[]),
            FL(from, prefix, offset) => looped(&mut b.fans, from, n.fans, prefix, offset, &[]),
            CL(from, prefix, offset) => looped(&mut b.controls, from, n.controls, prefix, offset, &[]),
            TX(prefix, skip) => looped(&mut b.temps, 0, n.temps, prefix, 0, skip),
        }
    }
    b
}

/// Wpis listy czujników.
#[derive(Clone, Copy, Debug)]
enum S {
    T(usize, &'static str),
    F(usize, &'static str),
    C(usize, &'static str),
    /// Pętla od indeksu do końca czujników układu: nazwa = prefiks + (i + przesunięcie).
    TL(usize, &'static str, isize),
    FL(usize, &'static str, isize),
    CL(usize, &'static str, isize),
    /// Pętla po wszystkich temperaturach z pominięciem indeksów: prefiks + i.
    TX(&'static str, &'static [usize]),
}

